/**
 * Node-only: reads the R2 package JSON and renders the runtime data module. Used by
 * tools/r2-import.mjs and by the sync test; never bundled.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const sha = text => crypto.createHash('sha256').update(text).digest('hex');
const num = x => Math.round(x * 1e7) / 1e7;

/**
 * R3 recreations (docs/papercraft/construction-r3/datos/Pxx-*.json, same schema as R2) replace the
 * R2 recipe with the same id; every other recipe, the assembly and the rig stay R2.
 */
export function readR2(dir, overridesDir = path.join(path.dirname(dir), 'construction-r3')) {
  const datos = path.join(dir, 'datos'), files = {}, overrides = {};
  const read = (name, base = datos, tag = 'datos') => { const text = fs.readFileSync(path.join(base, name), 'utf8'); files[`${tag}/${name}`] = sha(text); return JSON.parse(text); };
  const assembly = read('assembly.json');
  const recipes = {};
  const r3 = path.join(overridesDir, 'datos');
  const r3names = fs.existsSync(r3) ? fs.readdirSync(r3).filter(f => /^P\d\d-.*\.json$/.test(f)).sort() : [];
  const byId = new Map(r3names.map(name => [name.slice(0, 3), name]));
  for (const name of fs.readdirSync(datos).filter(f => /^P\d\d-.*\.json$/.test(f)).sort()) {
    const over = byId.get(name.slice(0, 3));
    const d = over ? read(over, r3, 'r3/datos') : read(name);
    if (over) {
      const r2 = JSON.parse(fs.readFileSync(path.join(datos, name), 'utf8'));
      overrides[d.id] = { file: `construction-r3/datos/${over}`, replaces: `construction-r2/datos/${name}`, triangles: d.mesh.faces.length, replacedTriangles: r2.mesh.faces.length };
    }
    recipes[d.id] = {
      id: d.id, slug: d.slug, name: d.name, purpose: d.purpose, construction: d.construction, limitations: d.metadata.limitations || [],
      kind: d.metadata.surface_kind, base: d.material.base_color_srgb.toUpperCase(),
      vertices: d.mesh.vertices.map(v => v.map(num)), faces: d.mesh.faces, colors: d.mesh.face_colors.map(c => c.toUpperCase()),
      sockets: Object.fromEntries(Object.entries(d.sockets).map(([k, s]) => [k, { at: s.position_local_H.map(num), ...(s.instance_scope ? { scope: s.instance_scope } : {}) }]))
    };
  }
  const instances = assembly.instances.map(i => ({
    id: i.id, recipe: i.part_id, bone: i.bone, position: i.position_H.map(num), rotation: i.rotation_deg_xyz, scale: i.scale_xyz, mirror: !!i.mirror_x,
    order: i.assembly_order, parent: i.mount?.parent_instance_id || null, source: i.mount?.source_socket || 'origin', target: i.mount?.target_socket || null
  }));
  const rig = Object.fromEntries(assembly.rig.map(r => [r.id, { parent: r.parent, at: r.rest_position_root_H.map(num) }]));
  return { files, assembly, recipes, instances, rig, overrides };
}

export function r2DataModule(dir) {
  const { files, assembly, recipes, instances, rig, overrides } = readR2(dir);
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'MANIFIESTO.json'), 'utf8'));
  const body = {
    PROVENANCE: { package: 'GuateGeeks_Primaria_Piezas_R2', assembly: assembly.id, schema: assembly.schema_version, manifest: manifest.package || manifest.name || null, sha256: files, r3: overrides },
    H: assembly.scale_to_scene, LANDMARKS_H: assembly.landmarks_H, BUDGET: assembly.budget, RIG_H: rig, RECIPES: recipes, INSTANCES: instances
  };
  const lines = ['// GENERATED by tools/r2-import.mjs from docs/papercraft/construction-r2 — do not edit.',
    '// Package GuateGeeks_Primaria_Piezas_R2: 20 recipes, 33 instances (assembly.json).'];
  for (const [k, v] of Object.entries(body)) lines.push(`export const ${k} = Object.freeze(${JSON.stringify(v)});`);
  return lines.join('\n') + '\n';
}
