// Run with `npm run dev` active. Uses the real GPU settings when GG_GPU=1.
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';

const out = process.argv[2] || '../runs/web-slice';
mkdirSync(out, { recursive: true });
const gpu = process.env.GG_GPU === '1';
const browser = await chromium.launch({ args: gpu ? ['--use-angle=gl', '--enable-gpu', '--ignore-gpu-blocklist'] : ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 880 } });
const problems = [];
page.on('pageerror', e => problems.push(String(e)));
page.on('console', m => { if (m.type() === 'error') problems.push(m.text()); });
await page.goto('http://127.0.0.1:4410/slice.html');
await page.waitForFunction(() => window.world?.getDiagnostics().ready, null, { timeout: 60000 });
await page.waitForTimeout(1500);
const d = await page.evaluate(() => window.world.getDiagnostics());
console.log(JSON.stringify(d));
await page.screenshot({ path: `${out}/overview.png` });
await page.evaluate(() => window.world.setFocus({ kind: 'room' }));
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/room.png` });
await page.evaluate(() => window.world.setFocus(null));
await page.mouse.move(700, 440);
await page.mouse.down();
await page.mouse.move(900, 440, { steps: 4 });
await page.mouse.up();
await page.waitForTimeout(400);
const after = await page.evaluate(() => window.world.getDiagnostics());
await page.screenshot({ path: `${out}/orbit.png` });
const reduced = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 390, height: 800 } });
const phone = await reduced.newPage();
await phone.goto('http://127.0.0.1:4410/slice.html');
await phone.waitForFunction(() => window.world?.getDiagnostics().ready, null, { timeout: 60000 });
await phone.waitForTimeout(800);
await phone.screenshot({ path: `${out}/phone.png` });
const overflow = await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await reduced.close();
const gone = await page.evaluate(() => { window.world.dispose(); return window.world.getDiagnostics(); });
const failures = [];
const expect = (ok, text) => { if (!ok) failures.push(text); };
expect(!overflow, 'phone view scrolls sideways');
expect(d.loaded === 11, `loaded ${d.loaded} of 11 assets`);
expect(d.errors.length === 0, `errors: ${d.errors}`);
expect(d.triangles > 0, 'nothing drawn');
expect(after.yaw !== d.yaw, 'drag did not rotate the view');
expect(gone.geometries === 0, `geometries left after dispose: ${gone.geometries}`);
expect(problems.length === 0, `page problems: ${problems.join(' | ')}`);
await browser.close();
if (failures.length) { console.error(failures.join('\n')); process.exit(1); }
console.log('PASS');
